#!/usr/bin/env python3
"""Regenerate data/tables_final.md from the packaged cards.

    python3 code/build_tables_final.py

Reads data/cards/*.json (129 cards) at runtime; no statistic is hardcoded.
Writes data/tables_final.md with three tables:
  Table 1 - core-research cards grouped by defense execution layer
  Table 2 - the operations x layers coverage matrix (occupied cells, zero cells marked)
  Table 3 - evidence-strength grading (measured / qualitative / design-position)
"""
import json
from collections import Counter, OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CARDS = ROOT / "data" / "cards"
OUT = ROOT / "data" / "tables_final.md"

LAYER_EN = {
    "content": "content filtering", "provenance": "provenance tracing",
    "execution": "execution-time gating", "architecture": "architecture isolation",
    "formal": "formal guarantees", "none": "no defense",
    "weight-space": "weight space", "evaluation": "evaluation",
    "prompt": "prompt", "memory": "memory", "mixed": "mixed",
}
OP_EN = {"formation": "formation", "update": "update", "retention": "retention",
         "retrieval": "retrieval", "revocation": "revocation", "repair": "repair"}
CARRIER_EN = {"memory": "memory", "skill": "skill", "experience": "experience",
              "policy": "policy/authz", "shared_state": "shared state", "mixed": "mixed",
              "none": "none"}
ADV_EN = {"external": "external", "user": "user", "none": "none", "insider": "insider",
          "model-itself": "model itself", "unclear": "unclear"}
QUAL_FLAGS = {"qualitative_success_only", "defense_evaluation_qualitative_only",
              "no_quantified_success_rates"}

cards = [json.load(open(p, encoding="utf-8")) for p in sorted(CARDS.glob("*.json"))]


def evidence_type(c):
    if len(c.get("results") or []) == 0:
        return "design/position"
    if set(c.get("quality_flags") or []) & QUAL_FLAGS:
        return "qualitative"
    return "measured"


def primary_value(c):
    res = c.get("results") or []
    return str(res[0].get("value")) if res else "-"


def trunc(s, n):
    s = " ".join(str(s or "").split())
    return s if len(s) <= n else s[: n - 1] + "..."


def layer_of(c):
    return (c.get("intervention") or {}).get("mechanism_layer") or "none"


LAYERS5 = ["content", "provenance", "execution", "architecture", "formal"]
OPS = ["formation", "update", "retention", "retrieval", "revocation", "repair"]

# ---- Table 2: the coverage matrix ----
M = {op: {l: 0 for l in LAYERS5} for op in OPS}
for c in cards:
    lay = layer_of(c)
    if lay not in LAYERS5:
        continue
    for op in (c.get("object") or {}).get("operations_covered") or []:
        if op in M:
            M[op][lay] += 1
row_tot = {op: sum(M[op].values()) for op in OPS}
col_tot = {l: sum(M[op][l] for op in OPS) for l in LAYERS5}
grand = sum(row_tot.values())
zero_cells = [(op, l) for op in OPS for l in LAYERS5 if M[op][l] == 0]

# ---- Table 3: evidence grading ----
ev = Counter(evidence_type(c) for c in cards)

# ---- Table 1: core cards grouped by layer ----
core = [c for c in cards if c.get("screening_status") == "核心研究"]
groups = OrderedDict()
for c in sorted(core, key=lambda x: x["arxiv_id"]):
    groups.setdefault(layer_of(c), []).append(c)

L = []
L.append("# tables-final.md - submission tables (regenerated from the 129 packaged cards)")
L.append("")
L.append("Generated by `code/build_tables_final.py`; reads `data/cards/*.json` at runtime,")
L.append("no statistic is hardcoded. Caliber: the 129-card corpus (12 later backfills included).")
L.append("Cards whose `intervention.mechanism_layer` is outside the five defense layers")
L.append("(none / weight-space / evaluation / prompt / memory / mixed) enter Table 1 under")
L.append("their own layer label but no matrix cell.")
L.append("")
L.append(f"Core-research cards: {len(core)} of {len(cards)}.")
L.append("")

# ===================== Table 1 =====================
L.append("## Table 1: core-research cards grouped by defense execution layer")
L.append("")
for lay, rows in groups.items():
    L.append(f"**{LAYER_EN.get(lay, lay)} ({len(rows)} cards)**")
    L.append("")
    L.append("| id | paper (short title) | carrier | operations | adversary | evidence | primary result (truncated) |")
    L.append("|---|---|---|---|---|---|---|")
    for c in rows:
        aid = c["arxiv_id"]
        ops = "/".join(OP_EN.get(o, o) for o in (c.get("object") or {}).get("operations_covered") or []) or "-"
        L.append("| `{}` | {} | {} | {} | {} | {} | {} |".format(
            aid, trunc(c.get("title"), 24),
            CARRIER_EN.get((c.get("object") or {}).get("what_persists"), "-"),
            trunc(ops, 34),
            ADV_EN.get((c.get("threat_model") or {}).get("adversary"), "-"),
            evidence_type(c), trunc(primary_value(c), 26)))
    L.append("")

# ===================== Table 2 =====================
L.append("## Table 2: coverage matrix - state operations x defense execution layers")
L.append("")
L.append(f"Cells = combinations of card `operations_covered` x `intervention.mechanism_layer`")
L.append(f"({len(cards)} cards, {grand} occupied cells). 0* = zero cell (no evidence in the corpus).")
L.append("")
L.append("| operation \\ layer | " + " | ".join(LAYER_EN[l] for l in LAYERS5) + " | row total |")
L.append("|---" * 7 + "|")
for op in OPS:
    cells = [f"{M[op][l]}*" if M[op][l] == 0 else str(M[op][l]) for l in LAYERS5]
    L.append(f"| {OP_EN[op]} | " + " | ".join(cells) + f" | **{row_tot[op]}** |")
L.append("| **column total** | " + " | ".join(f"**{col_tot[l]}**" for l in LAYERS5) + f" | **{grand}** |")
L.append("")
L.append("Zero cells: " + (", ".join(f"{OP_EN[op]} x {LAYER_EN[l]}" for op, l in zero_cells) or "none")
         + f" ({len(zero_cells)} of 30).")
L.append("Column totals: " + ", ".join(f"{LAYER_EN[l]} {col_tot[l]}" for l in LAYERS5) + ".")
L.append("")

# ===================== Table 3 =====================
L.append("## Table 3: evidence-strength grading")
L.append("")
L.append("| grade | cards | share | criterion |")
L.append("|---|---:|---:|---|")
for k, crit in [("measured", "results non-empty and no qualitative-only flag"),
                ("qualitative", "quality_flags contain a qualitative-only flag"),
                ("design/position", "results is empty (0 results)")]:
    L.append(f"| {k} | {ev[k]} | {ev[k]/len(cards)*100:.1f}% | {crit} |")
L.append(f"| **total** | **{len(cards)}** | 100.0% | denominator: all {len(cards)} cards |")
L.append("")

OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
print(f"written: {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")
print(f"core cards: {len(core)} | layer groups: "
      + ", ".join(f"{LAYER_EN.get(k, k)}={len(v)}" for k, v in groups.items()))
print(f"matrix grand={grand} | rows=" + "/".join(str(row_tot[o]) for o in OPS)
      + " | cols=" + "/".join(str(col_tot[l]) for l in LAYERS5))
print(f"zero cells: {zero_cells}")
print(f"evidence: {dict(ev)}")
